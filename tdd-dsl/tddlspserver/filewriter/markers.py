"""Marker comments of generated Fortran stubs.

The Jinja templates write these markers into generated functions and subroutines; the file writer and the fxtran
analysis recognize generated stubs by them. Keep all three in sync by using only the constants of this module.
"""

from typing import Tuple

#: Placeholder for the missing return type of a generated function
RETURN_TYPE_MARKER: str = "! <<Add return type here>>"
#: Placeholder for the missing return expression of a generated function
RETURN_EXPRESSION_MARKER: str = "! <<Add return expression here>>"


def body_marker(routine_type: str) -> str:
    """Placeholder for the missing body of a generated routine of the given type (FUNCTION or SUBROUTINE)."""
    return f"! <<Add {routine_type} body here>>"


#: Markers that identify a stub as generated and not yet implemented
GENERATED_MARKERS: Tuple[str, ...] = (RETURN_EXPRESSION_MARKER, body_marker("SUBROUTINE"), body_marker("FUNCTION"))

#: Markers of files generated by earlier versions of the templates
LEGACY_MARKERS: Tuple[str, ...] = ("! <<Replace with return expression here>>",
                                   "! <<Replace with SUBROUTINE body here>>")

#: All markers recognized in existing files, case-insensitive like Fortran
RECOGNIZED_MARKERS: Tuple[str, ...] = GENERATED_MARKERS + LEGACY_MARKERS


def contains_marker(text: str) -> bool:
    """Whether the text contains the marker of a generated, not yet implemented stub."""
    lowered = text.lower()
    return any(marker.lower() in lowered for marker in RECOGNIZED_MARKERS)
